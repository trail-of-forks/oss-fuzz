cd fuzz

# Generate seed corpus files
chmod +x generate_seeds.sh
./generate_seeds.sh

make all

# Copy fuzzers
cp FuzzClient $OUT/FuzzClient
cp FuzzServer $OUT/FuzzServer
cp FuzzClientWrite $OUT/FuzzClientWrite
cp FuzzClientRead $OUT/FuzzClientRead
cp FuzzServerRTU $OUT/FuzzServerRTU
cp FuzzDataConversion $OUT/FuzzDataConversion

# Copy dictionary (used by all fuzzers)
cp modbus.dict $OUT/modbus.dict
cp modbus.dict $OUT/FuzzServer.dict
cp modbus.dict $OUT/FuzzClient.dict
cp modbus.dict $OUT/FuzzClientWrite.dict
cp modbus.dict $OUT/FuzzClientRead.dict
cp modbus.dict $OUT/FuzzServerRTU.dict
cp modbus.dict $OUT/FuzzDataConversion.dict

# Copy seed corpora (generated by generate_seeds.sh)
cp FuzzServer_seed_corpus.zip $OUT/FuzzServer_seed_corpus.zip
cp FuzzClient_seed_corpus.zip $OUT/FuzzClient_seed_corpus.zip
cp FuzzClientWrite_seed_corpus.zip $OUT/FuzzClientWrite_seed_corpus.zip
cp FuzzClientRead_seed_corpus.zip $OUT/FuzzClientRead_seed_corpus.zip
cp FuzzServerRTU_seed_corpus.zip $OUT/FuzzServerRTU_seed_corpus.zip
cp FuzzDataConversion_seed_corpus.zip $OUT/FuzzDataConversion_seed_corpus.zip

# Also copy from oss-fuzz-bloat if available (original seeds)
if [ -d "$SRC/oss-fuzz-bloat/libmodbus/" ]; then
    pushd $SRC/oss-fuzz-bloat/libmodbus/
    # Merge with existing if they exist
    if [ -f FuzzClient_seed_corpus.zip ]; then
        cp FuzzClient_seed_corpus.zip $OUT/FuzzClient_seed_corpus_bloat.zip || true
    fi
    if [ -f FuzzServer_seed_corpus.zip ]; then
        cp FuzzServer_seed_corpus.zip $OUT/FuzzServer_seed_corpus_bloat.zip || true
    fi
    popd
fi
